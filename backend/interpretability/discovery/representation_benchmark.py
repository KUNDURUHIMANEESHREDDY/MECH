"""Representation Benchmark Suite — Evaluating Scientific Rigor.

Systematically evaluates discovered concepts across multiple domains:
- Geography: Capitals, Cities, Countries.
- Code: Python Syntax, Logic, Loops.
- Math: Numbers, Addition, Comparisons.
- Logic: Negation, Conjunction, Inference.

Metrics:
- Purity: Do features in the cluster fire on only the target category?
- Completeness: Does the representation capture all instances of the category?
- Alignment: Consistency across models and layers.

What this used to return
------------------------
`run_benchmark(model_results)` ignored `model_results` entirely and computed
both metrics from a hash of its own task names:

    purity = 0.88 + (hash(task.domain) % 10) / 100.0
    completeness = 0.74 + (hash(task.target_concept) % 15) / 100.0

So it reported purity between 0.88 and 0.97 and completeness between 0.74 and
0.88, for every task, on every run, without loading a model or looking at a
single activation. `overall_rigor` came out near 0.85 and `threshold` defaults
to 0.75, so the benchmark passed by construction. It is fabricated evidence
generated by arithmetic, and `overall_rigor` was named and shaped to be
mistaken for a measurement.

Worse than a stub returning 0.94, which this repository is built to refuse: a
stub is at least obviously a stub. This produced numbers in the plausible range
for a real result, and because Python randomises string hashing per process,
they *changed between runs* while looking like measurements. A fabricated
result that is also irreproducible defeats the reproducibility checks too.

There is now no path that produces a number without cluster assignments to
compute it from. `run_benchmark` requires the assignment a clustering actually
produced and returns `unavailable` with a reason when it does not have one.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Sequence, Tuple


@dataclass
class BenchmarkTask:
    domain: str
    target_concept: str
    expected_features: List[str]
    threshold: float = 0.75


class RepresentationBenchmark:
    """Orchestrates multi-domain representation benchmarks."""

    def __init__(self) -> None:
        self.tasks = [
            BenchmarkTask("Geography", "European Capitals", ["L8_F1402", "L8_F1510"]),
            BenchmarkTask("Code", "Python Function Definitions", ["L4_F892"]),
            BenchmarkTask("Logic", "Negation", ["L2_F12"])
        ]

    @staticmethod
    def _assignments_for(model_results: Any, task: BenchmarkTask
                         ) -> Tuple[Optional[str], Optional[List[Tuple[Any, Any]]], str]:
        """Pull the target concept and the `(predicted, true)` pairs for a task.

        The concept label has to be declared rather than inferred. Purity and
        completeness are only well defined against a named concept, and the
        tempting shortcut -- assuming the predicted label and the true label
        live in the same namespace, so `true == predicted_cluster` identifies
        the concept -- is wrong in a way that scores perfectly. Four items in
        four single-member clusters, every one of them internally consistent,
        comes out as purity 1.0 and completeness 1.0.

        Accepted shape, per task:

            {"concept": <label>, "assignments": [[predicted, true], ...]}

        or `assignments` as a mapping of predicted label -> list of true labels.
        """
        if not isinstance(model_results, dict) or not model_results:
            return None, None, "no model results were supplied"

        entry = model_results.get(task.target_concept)
        if entry is None:
            entry = model_results.get(task.domain)
        if entry is None:
            return None, None, (f"no cluster assignments were supplied for "
                                f"{task.target_concept!r}")
        if not isinstance(entry, dict):
            return None, None, (
                f"assignments for {task.target_concept!r} must be a mapping with "
                f"'concept' and 'assignments' keys; got {type(entry).__name__}")

        concept = entry.get("concept")
        if concept is None:
            return None, None, (
                f"assignments for {task.target_concept!r} do not declare which "
                f"true label is the target concept, so purity and completeness "
                f"cannot be computed")

        raw = entry.get("assignments")
        if isinstance(raw, dict):
            pairs: List[Tuple[Any, Any]] = [
                (predicted, true)
                for predicted, trues in raw.items()
                for true in (trues if isinstance(trues, (list, tuple)) else [trues])
            ]
        elif isinstance(raw, (list, tuple)):
            pairs = []
            for item in raw:
                if not isinstance(item, (list, tuple)) or len(item) != 2:
                    return None, None, (
                        f"cluster assignments for {task.target_concept!r} must "
                        f"be (predicted, true) pairs; got {item!r}")
                pairs.append((item[0], item[1]))
        else:
            return None, None, (
                f"'assignments' for {task.target_concept!r} must be a list of "
                f"pairs or a mapping; got {type(raw).__name__}")

        if not pairs:
            return None, None, f"cluster assignments for {task.target_concept!r} are empty"
        if not any(true == concept for _, true in pairs):
            return None, None, (
                f"no assignment for {task.target_concept!r} has true label "
                f"{concept!r}, so there is nothing to measure")
        return concept, pairs, ""

    @staticmethod
    def _score(pairs: Sequence[Tuple[Any, Any]], concept: Any) -> Dict[str, Any]:
        """Purity and completeness of one clustering, against a named concept.

        Purity: of the items assigned to the cluster that captured most of the
        concept, the fraction that really are the concept. Low when the cluster
        also contains things that are not.

        Completeness: of everything that really is the concept, the fraction the
        clustering captured. Low when the concept is spread across clusters.

        The two move independently, which is the point of reporting both: four
        single-member clusters are perfectly pure and capture nothing, while one
        cluster holding the concept plus everything else is complete and pure in
        one item and useless in the other.
        """
        total_true = sum(1 for _, true in pairs if true == concept)
        sizes: Dict[Any, int] = {}
        for predicted, _ in pairs:
            sizes[predicted] = sizes.get(predicted, 0) + 1

        def rank(label: Any) -> tuple:
            captured = sum(1 for p, t in pairs if p == label and t == concept)
            # Most true positives wins; ties go to the smaller cluster (a
            # purer claim) and then to a stable string order.
            return (captured, -sizes[label], str(label))

        matched_label = max(sizes, key=rank)
        matched = [(p, t) for p, t in pairs if p == matched_label]
        correct = sum(1 for _, true in matched if true == concept)

        purity = correct / len(matched) if matched else 0.0
        completeness = correct / total_true if total_true else 0.0
        return {
            "purity": round(purity, 4),
            "completeness": round(completeness, 4),
            "overall": round((purity + completeness) / 2, 4),
            "concept": concept,
            "matched_cluster": matched_label,
            "n_assigned": len(pairs),
            "n_concept_items": total_true,
        }

    def run_benchmark(self, model_results: Dict[str, Any]) -> Dict[str, Any]:
        """Evaluate model discovery results against canonical tasks.

        Returns `provenance: "unavailable"` and no scores when it has no cluster
        assignments to compute them from. An absent measurement is reported as
        absent; it is never replaced by a plausible number.
        """
        scores: Dict[str, Any] = {}
        unmeasured: Dict[str, str] = {}

        for task in self.tasks:
            concept, pairs, problem = self._assignments_for(model_results, task)
            if problem:
                unmeasured[task.target_concept] = problem
                continue
            scores[task.target_concept] = self._score(pairs, concept)

        if not scores:
            return {
                "status": "blocked",
                "benchmark_id": "REPRO-v1.4",
                "provenance": "unavailable",
                "validation_eligible": False,
                "publication_eligible": False,
                "domain_scores": {},
                "overall_rigor": None,
                "tasks_measured": 0,
                "tasks_total": len(self.tasks),
                "unmeasured": unmeasured,
                "reason": ("No task had cluster assignments to score, so no "
                           "metric can be computed. Purity and completeness are "
                           "properties of an assignment; without one there is "
                           "nothing to report."),
            }

        return {
            "status": "completed",
            "benchmark_id": "REPRO-v1.4",
            # "reference", not "live". The scores below are a real computation,
            # but over assignments this function was handed: it did not run a
            # model, and it cannot tell whether the assignments came from a
            # measured clustering or from a fixture. Claiming "live" would be
            # the same overclaim the hash-derived version made, one level up.
            # A caller that has an attested clustering in hand should admit it
            # through EvidenceBoundary, which is what decides provenance.
            "provenance": "reference",
            "validation_eligible": False,
            "publication_eligible": False,
            "domain_scores": scores,
            "overall_rigor": (sum(s["overall"] for s in scores.values())
                              / len(scores)),
            "tasks_measured": len(scores),
            "tasks_total": len(self.tasks),
            "unmeasured": unmeasured,
            "reason": (None if not unmeasured else
                       f"{len(unmeasured)} of {len(self.tasks)} tasks had no "
                       f"cluster assignments and are excluded from the average."),
        }
