class ArchiveBuilder:
    """Creates verifiable JSON packages and ZIP archives for immutable experiment runs."""

    @staticmethod
    def build_archive_dict(run: ImmutableExperimentRun) -> Dict[str, str]:
        """Builds all text contents and calculates manifest.json SHA-256 map."""
        exp_json = json.dumps(run.specification.to_dict(), indent=2)
        env_json = json.dumps(run.environment.to_dict(), indent=2)
        meas_json = json.dumps(run.measurements, indent=2)
        controls_json = json.dumps(run.provenance_chain.four_control_results, indent=2)
        null_json = json.dumps({
            "percentile": run.provenance_chain.null_distribution_percentile,
            "p_value": run.provenance_chain.null_distribution_p_value,
        }, indent=2)
        model_json = json.dumps(run.model.to_dict(), indent=2)
        reproduce_py = generate_standalone_reproduce_script(run)
        readme_md = generate_readme_md(run)

        manifest = {
            "archive_format": "MECH_EXPERIMENT_ARCHIVE_V1",
            "run_id": run.run_id,
            "experiment_type": run.experiment_type,
            "timestamp_utc": run.timestamp_utc,
            "files": {
                "experiment.json": _hash_str(exp_json),
                "environment.json": _hash_str(env_json),
                "measurements.json": _hash_str(meas_json),
                "controls.json": _hash_str(controls_json),
                "null_distribution.json": _hash_str(null_json),
                "model_manifest.json": _hash_str(model_json),
                "reproduce.py": _hash_str(reproduce_py),
                "README.md": _hash_str(readme_md),
            }
        }
        manifest_json = json.dumps(manifest, indent=2)

        return {
            "manifest.json": manifest_json,
            "experiment.json": exp_json,
            "environment.json": env_json,
            "measurements.json": meas_json,
            "controls.json": controls_json,
            "null_distribution.json": null_json,
            "model_manifest.json": model_json,
            "reproduce.py": reproduce_py,
            "README.md": readme_md,
        }

    @staticmethod
    def build_zip_bytes(run: ImmutableExperimentRun) -> bytes:
        """Packages the archive into an in-memory ZIP file."""
        files = ArchiveBuilder.build_archive_dict(run)
        buffer = BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
            for filename, content in files.items():
                zip_file.writestr(filename, content)
        buffer.seek(0)
        return buffer.getvalue()
