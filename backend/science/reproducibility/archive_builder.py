def _hash_str(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def generate_standalone_reproduce_script(run: ImmutableExperimentRun) -> str:
    """Generates a standalone Python reproduction script that executes outside MECH."""
    spec = run.specification
    model = run.model
    meas = run.measurements

    return f'''"""Standalone Reproduction Script for MECH Experiment '{run.run_id}'.

Generated by MECH Platform (Phase 11 Reproducibility Engine).
Run with: python reproduce.py
"""

import json
import sys
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

EXPECTED_RESULTS = {{
    "clean_logit": {meas.get("clean_logit", 0.0)},
    "intervened_logit": {meas.get("intervened_logit", 0.0)},
    "delta_logit": {meas.get("delta_logit", 0.0)},
    "clean_rank": {meas.get("clean_rank", 0)},
    "intervened_rank": {meas.get("intervened_rank", 0)},
    "clean_probability": {meas.get("clean_probability", 0.0)},
    "intervened_probability": {meas.get("intervened_probability", 0.0)},
}}

SPECIFICATION = {{
    "model_id": "{model.model_id}",
    "clean_prompt": "{spec.clean_prompt}",
    "target_token": "{spec.target_token}",
    "layer": {spec.layer},
    "component_type": "{spec.component_type}",
    "component_index": {spec.component_index},
    "ablation_scale": {spec.ablation_scale},
    "random_seed": {spec.random_seed},
}}

def main():
    print("=" * 70)
    print(f"MECH REPRODUCTION AUDIT: {{SPECIFICATION['model_id']}} on '{{SPECIFICATION['clean_prompt']}}'")
    print("=" * 70)

    torch.manual_seed(SPECIFICATION["random_seed"])
    print(f"1. Loading model '{{SPECIFICATION['model_id']}}'...")
    tokenizer = AutoTokenizer.from_pretrained(SPECIFICATION["model_id"])
    model = AutoModelForCausalLM.from_pretrained(SPECIFICATION["model_id"])
    model.eval()

    # Verify target token
    target_ids = tokenizer.encode(SPECIFICATION["target_token"])
    target_id = target_ids[-1]
    print(f"2. Target token: '{{SPECIFICATION['target_token']}}' (ID: {{target_id}})")

    # 3. Clean Run
    inputs = tokenizer(SPECIFICATION["clean_prompt"], return_tensors="pt")
    with torch.no_grad():
        clean_out = model(**inputs)
    clean_logits = clean_out.logits[0, -1]
    clean_target_logit = float(clean_logits[target_id].item())
    clean_probs = torch.softmax(clean_logits, dim=-1)
    clean_target_prob = float(clean_probs[target_id].item())
    clean_rank = int((clean_logits > clean_target_logit).sum().item())

    print(f"3. Clean Run: Logit={{clean_target_logit:.4f}}, Prob={{clean_target_prob:.4f}}, Rank={{clean_rank}}")

    # 4. Forward hook intervention
    layer_idx = SPECIFICATION["layer"]
    neuron_idx = SPECIFICATION["component_index"]
    scale = SPECIFICATION["ablation_scale"]

    def hook_fn(module, input, output):
        # Zero/scale ablate component
        if isinstance(output, tuple):
            act = output[0].clone()
            if act.shape[-1] > neuron_idx:
                act[:, :, neuron_idx] *= scale
            return (act,) + output[1:]
        act = output.clone()
        if act.shape[-1] > neuron_idx:
            act[:, :, neuron_idx] *= scale
        return act

    hook_handle = None
    if hasattr(model, "transformer") and hasattr(model.transformer, "h"):
        target_layer = model.transformer.h[layer_idx].mlp.c_fc
        hook_handle = target_layer.register_forward_hook(hook_fn)

    try:
        with torch.no_grad():
            intervened_out = model(**inputs)
    finally:
        if hook_handle:
            hook_handle.remove()

    intervened_logits = intervened_out.logits[0, -1]
    intervened_target_logit = float(intervened_logits[target_id].item())
    intervened_probs = torch.softmax(intervened_logits, dim=-1)
    intervened_target_prob = float(intervened_probs[target_id].item())
    intervened_rank = int((intervened_logits > intervened_target_logit).sum().item())
    delta_logit = clean_target_logit - intervened_target_logit

    print(f"4. Intervened: Logit={{intervened_target_logit:.4f}}, Prob={{intervened_target_prob:.4f}}, Rank={{intervened_rank}}")
    print(f"5. Measured Causal Delta z: {{delta_logit:.4f}}")

    # 5. Assertions within numerical tolerance (abs <= 1e-3)
    diff = abs(delta_logit - EXPECTED_RESULTS["delta_logit"])
    print("-" * 70)
    print(f"TOLERANCE CHECK: |delta_obs - delta_exp| = {{diff:.2e}}")
    if diff <= 1e-3:
        print(">> VERDICT: REPRODUCED SUCCESSFULLY WITHIN NUMERICAL TOLERANCE <<")
        sys.exit(0)
    else:
        print(">> VERDICT: NUMERICAL DIVERGENCE DETECTED <<")
        sys.exit(1)

if __name__ == "__main__":
    main()
'''


